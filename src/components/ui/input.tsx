import * as React from "react";
import { cn } from "@/lib/utils";

export const Input = React.forwardRef<HTMLInputElement, React.InputHTMLAttributes<HTMLInputElement>>(
  ({ className, type = "text", ...props }, ref) => (
    <input
      ref={ref}
      type={type}
      className={cn(
        // 16px base font on mobile stops iOS Safari zooming on focus.
        "flex h-10 w-full rounded-md border border-input bg-card px-3 py-2 text-base sm:text-sm",
        "placeholder:text-muted-foreground",
        "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-1 focus-visible:ring-offset-background",
        "disabled:cursor-not-allowed disabled:opacity-50",
        "aria-[invalid=true]:border-danger aria-[invalid=true]:ring-danger",
        // type="file" otherwise renders the browser's own grey button inside
        // our box, at whatever height the platform picks.
        "file:mr-3 file:h-6 file:rounded file:border file:border-border file:bg-muted file:px-2.5",
        "file:text-sm file:font-medium file:text-foreground hover:file:bg-border",
        className,
      )}
      {...props}
    />
  ),
);
Input.displayName = "Input";

